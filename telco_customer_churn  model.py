import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
    classification_report,
    roc_auc_score,
    roc_curve
)

"""we call the libraries we need for an clasification model if it was like regretion its different"""

data = pd.read_csv("Telco_Customer_Churn_Cleaned.csv")

print("Dataset loaded successfully.")
print("Dataset shape:", data.shape)

"""we upload the cleaned dataset"""

X = data.drop(columns=["Churn"])
y = data["Churn"]

print("\nFeature columns:", X.columns.tolist())
print("X shape:", X.shape)
print("y shape:", y.shape)

"""we choose the target and featuers so the target is churn and the ohter columns is the fea..."""

print("\nChurn distribution:")
print(y.value_counts(normalize=True) * 100)

"""see the percent of the churn
73% stay
27% leave
"""

X_train, X_test, y_train, y_test = train_test_split(
    X, y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("\nTraining data shape:", X_train.shape)
print("Testing data shape:", X_test.shape)

"""We divide the data into training (80%) and testing (20%)
The new addition here is stratify=y - this ensures that the ratio of 73/27 remains the same in both the training set and the test set. Without it, you may accidentally have a different distribution between the two, and this will affect the accuracy of the evaluation.
"""

scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

print("\nFeature scaling completed.")

"""We standardize all columns (mean=0, standard deviation=1) because no column “dominates” just because it has larger numbers. Also note: fit_transform on train only, and transform only on test — for the same reason (preventing data leakage)."""

model = LogisticRegression(max_iter=1000)

model.fit(X_train_scaled, y_train)

print("Model training completed.")

"""Create and Train the Model
max_iter=1000 gives the model a greater chance of converging on the best solution during training (sometimes it needs more attempts than the default).
"""

predictions = model.predict(X_test_scaled)
probabilities = model.predict_proba(X_test_scaled)[:, 1]

print("\nFirst ten predictions (0/1):")
print(predictions[:10])

print("\nFirst ten churn probabilities:")
print(np.round(probabilities[:10], 3))

"""Make Predictions
Here is an important difference from Regression: we have two types of expectation. predict() gives you a final decision (0 or 1). predict_proba() gives you the model's confidence level as a percentage (for example, 0.82 means the model is 82% confident that this customer will leave). Probabilities are more useful than a final decision in many situations, because they give you flexibility to change the “decision limit” later.
"""

accuracy = accuracy_score(y_test, predictions)
precision = precision_score(y_test, predictions)
recall = recall_score(y_test, predictions)
f1 = f1_score(y_test, predictions)
auc = roc_auc_score(y_test, probabilities)

print("\n" + "=" * 45)
print("MODEL EVALUATION METRICS")
print("=" * 45)
print("Accuracy :", round(accuracy, 4))
print("Precision:", round(precision, 4))
print("Recall   :", round(recall, 4))
print("F1 Score :", round(f1, 4))
print("AUC      :", round(auc, 4))
print("=" * 45)

"""Evaluation Metrics
Accuracy — the percentage of correct predictions out of all. Warning: Since the data is imbalanced (73/27), a stupid model that expects "0" for all clients will achieve about 73% accuracy without actually learning anything. It is never enough alone.
Precision — Of all the models who said “they will leave,” how many actually left? Important if you want to avoid false alarms.
Recall - Of all the people who actually left, how many were caught by the model? This is very important because the company's goal is usually "to catch as many people as possible who are vulnerable to abandonment."
F1 Score — A balanced average between Precision and Recall at a single digit.
AUC — the ability of the model to differentiate between the two categories in general.
"""

cm = confusion_matrix(y_test, predictions)

plt.figure(figsize=(6, 5))
sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="Blues",
    xticklabels=["No Churn", "Churn"],
    yticklabels=["No Churn", "Churn"]
)
plt.title("Confusion Matrix")
plt.xlabel("Predicted")
plt.ylabel("Actual")
plt.tight_layout()
plt.show()

"""Confusion Matrix
This is the most important visualization in a classification project. I show you four cases: a correct prediction “he will not leave” but he actually left, a correct prediction “he will leave” but he actually left, an incorrect prediction “he will leave” but he did not leave (false alarm), and an incorrect prediction “he will not leave” but he actually left — and this is the most dangerous case in practice, because the company loses a client without taking any preventive measures.
"""

fpr, tpr, thresholds = roc_curve(y_test, probabilities)

plt.figure(figsize=(7, 6))
plt.plot(fpr, tpr, label=f"AUC = {auc:.3f}")
plt.plot([0, 1], [0, 1], linestyle="--", color="gray")
plt.title("ROC Curve")
plt.xlabel("False Positive Rate")
plt.ylabel("True Positive Rate")
plt.legend()
plt.tight_layout()
plt.show()

"""A completely new step, which was not present in the Regression project at all. The ROC Curve is intended for classification only, and shows how the model balances between “catching true abandonments” versus “giving false alarms” at different confidence levels. The closer the curve is to the upper left corner, the stronger the model."""

